#!/usr/bin/env python3
"""Independent reference of ethash, written from the specification.

Our core/ethash.c was rewritten from the decompiled firmware: rereading it
proves nothing. A second implementation, obtained another way, is compared
with it. This one comes from the Ethash specification published by Ethereum,
not from the binary, and its Keccak is Cryptodome's, not ours: the two paths
share nothing but the algorithm, so if they agree on non-trivial inputs, an
error would have to be in the algorithm itself.

    python3 tools/ref_ethash.py > tools/vecteurs_ethash.h
"""
import struct

from Cryptodome.Hash import keccak

HASH_BYTES = 64
MIX_BYTES = 128
DATASET_PARENTS = 256
CACHE_ROUNDS = 3
ACCESSES = 64
FNV_PRIME = 0x01000193
EPOCH_LENGTH = 30000


def k512(b):
    return keccak.new(digest_bits=512, data=bytes(b)).digest()


def k256(b):
    return keccak.new(digest_bits=256, data=bytes(b)).digest()


def mots(b):
    return list(struct.unpack("<%dI" % (len(b) // 4), b))


def octets(w):
    return struct.pack("<%dI" % len(w), *w)


def fnv(a, b):
    return ((a * FNV_PRIME) ^ b) & 0xffffffff


def graine(bloc):
    s = b"\0" * 32
    for _ in range(bloc // EPOCH_LENGTH):
        s = k256(s)
    return s


def mkcache(taille, seed):
    n = taille // HASH_BYTES
    o = [k512(seed)]
    for _ in range(1, n):
        o.append(k512(o[-1]))
    for _ in range(CACHE_ROUNDS):
        for i in range(n):
            v = mots(o[i])[0] % n
            melange = bytes(x ^ y for x, y in zip(o[(i - 1 + n) % n], o[v]))
            o[i] = k512(melange)
    return o


def element_dag(cache, i):
    n = len(cache)
    r = HASH_BYTES // 4
    mix = mots(cache[i % n])
    mix[0] ^= i
    mix = mots(k512(octets(mix)))
    for j in range(DATASET_PARENTS):
        idx = fnv(i ^ j, mix[j % r]) % n
        parent = mots(cache[idx])
        mix = [fnv(a, b) for a, b in zip(mix, parent)]
    return k512(octets(mix))


def hashimoto_light(cache, taille_dag, entete, nonce):
    n = taille_dag // HASH_BYTES
    w = MIX_BYTES // 4
    par_page = MIX_BYTES // HASH_BYTES
    s = k512(entete + struct.pack("<Q", nonce))
    sm = mots(s)
    mix = sm * par_page
    for i in range(ACCESSES):
        p = fnv(i ^ sm[0], mix[i % w]) % (n // par_page) * par_page
        neuf = []
        for j in range(par_page):
            neuf += mots(element_dag(cache, p + j))
        mix = [fnv(a, b) for a, b in zip(mix, neuf)]
    cmix = []
    for i in range(0, len(mix), 4):
        cmix.append(fnv(fnv(fnv(mix[i], mix[i + 1]), mix[i + 2]), mix[i + 3]))
    return octets(cmix), k256(s + octets(cmix))


def hexa(b):
    return ", ".join("0x%02x" % x for x in b)


def main():
    seed = bytes(range(32))                 # non-trivial, non-zero seed
    taille_cache = 1024                     # 16 nodes: fast, and everything is exercised
    taille_dag = 8192                       # 64 pages of 128 bytes
    cache = mkcache(taille_cache, seed)

    print("/* Ethash vectors — GENERATED by tools/ref_ethash.py, do not edit")
    print(" * by hand. Reference: the Ethash specification and Cryptodome's")
    print(" * Keccak, two sources foreign to our code. */")
    print("#define VEC_CACHE_SIZE %d" % taille_cache)
    print("#define VEC_DAG_SIZE   %d" % taille_dag)
    print("static const uint8_t VEC_SEED[32] = { %s };" % hexa(seed))

    print("\n/* ethash_compute_cache_nodes: first and last node of the cache */")
    print("static const uint8_t VEC_CACHE0[64] = { %s };" % hexa(cache[0]))
    print("static const uint8_t VEC_CACHEN[64] = { %s };" % hexa(cache[-1]))

    print("\n/* ethash_calculate_dag_item, indices 0, 1, 17, 4095 */")
    for i in (0, 1, 17, 4095):
        print("static const uint8_t VEC_DAG%d[64] = { %s };"
              % (i, hexa(element_dag(cache, i))))

    entete = bytes((x * 7 + 3) & 0xff for x in range(32))
    nonce = 0x0123456789abcdef
    mixhash, resultat = hashimoto_light(cache, taille_dag, entete, nonce)
    print("\n/* ethash_hash: non-trivial header, nonce 0x0123456789abcdef */")
    print("static const uint8_t VEC_HEADER[32] = { %s };" % hexa(entete))
    print("#define VEC_NONCE 0x0123456789abcdefull")
    print("static const uint8_t VEC_MIXHASH[32] = { %s };" % hexa(mixhash))
    print("static const uint8_t VEC_RESULT[32] = { %s };" % hexa(resultat))

    print("\n/* ethash_get_seedhash: epochs 0, 1, 2 and 100 */")
    for bloc in (0, 30000, 60000, 3000000):
        print("static const uint8_t VEC_SEED_%d[32] = { %s };"
              % (bloc, hexa(graine(bloc))))


if __name__ == "__main__":
    main()
